package dev.ribod.storestudio.gradle.tasks

import dev.ribod.storestudio.model.ManifestEntry
import dev.ribod.storestudio.model.SourceLocation
import dev.ribod.storestudio.model.StoreManifest
import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Aggregates all discovered KSP module manifests into a consolidated execution manifest.
 *
 * Verifies that screenshot and feature graphic identifiers are unique across all modules,
 * reporting detailed source file locations when conflicts occur.
 */
public abstract class MergeStoreManifestTask : DefaultTask() {

    /** Collection of per-module `store-manifest.json` files generated by KSP. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    public abstract val manifestFiles: ConfigurableFileCollection

    /** Consolidated output manifest consumed by downstream rendering and export tasks. */
    @get:OutputFile
    public abstract val mergedManifest: RegularFileProperty

    init {
        group = "store studio"
        description = "Merges module manifests into a consolidated execution manifest."
    }

    @TaskAction
    public fun merge() {
        val destination = mergedManifest.get().asFile
        destination.parentFile.mkdirs()

        val idToLocation = mutableMapOf<String, SourceLocation>()
        val allEntries = mutableListOf<ManifestEntry>()

        val seenFiles = mutableSetOf<String>()
        for (file in manifestFiles.files) {
            if (!file.isFile || file.length() == 0L || !seenFiles.add(file.canonicalPath)) continue

            val manifest = StoreManifest.decodeFromString(file.readText())
            for (entry in manifest.entries) {
                val previous = idToLocation[entry.id]
                // KMP modules emit the same declaration from several compilations
                // (e.g. androidMain and commonMain metadata); keep the first occurrence.
                if (previous == entry.source) continue
                if (previous != null) {
                    error(
                        "Store Studio: Duplicate screenshot identifier '${entry.id}' detected.\n" +
                            "First declared at: ${previous.path}:${previous.line}\n" +
                            "Conflicting declaration at: ${entry.source.path}:${entry.source.line}",
                    )
                }
                idToLocation[entry.id] = entry.source
                allEntries.add(entry)
            }
        }

        // Sort deterministically to maintain reproducible manifests
        val sortedEntries = allEntries.sortedBy { it.id }
        val consolidated = StoreManifest(
            schemaVersion = 1,
            module = "consolidated",
            generator = "store-studio-gradle-plugin",
            entries = sortedEntries,
        )

        destination.writeText(StoreManifest.encodeToString(consolidated))
        logger.lifecycle(
            "Store Studio: Consolidated ${sortedEntries.size} entries " +
                "into ${destination.absolutePath}",
        )
    }
}
