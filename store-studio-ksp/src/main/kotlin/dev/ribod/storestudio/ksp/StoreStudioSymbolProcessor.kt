import dev.ribod.storestudio.model.StoreManifest
import java.io.File

/**
 * Kotlin Symbol Processor (KSP 2.x) that statically extracts and validates composable screens.
 *
 * Scans top-level functions annotated with [@StoreScreenshot] or [@StoreFeatureGraphic],
 * enforces strict compile-time constraints, resolves JVM bytecode method signatures,
 * and serializes an incremental [StoreManifest] into `META-INF/store-studio/store-manifest.json`.
 *
 * @param codeGenerator KSP file creation interface for generated output resources.
 * @param logger Compiler diagnostic logger for errors and warnings.
 * @param modulePath Gradle module path (e.g. `":feature:onboarding"`).
 * @param projectRootDir Absolute path to repository root directory for path relativization.
 */
public class StoreStudioSymbolProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
    private val modulePath: String,
    private val projectRootDir: String,
) : SymbolProcessor {

    private val idToLocationMap: MutableMap<String, SourceLocation> = mutableMapOf()

    // Collected across rounds (later rounds see functions generated by other processors) and
    // written once in finish(), as the manifest aggregates the whole module.
    private val entries = mutableListOf<ManifestEntry>()
    private val originatingFiles = mutableSetOf<KSFile>()

    // Resolved once per module/file instead of once per annotated function
    private val canonicalRoot: File? by lazy {
        runCatching { File(projectRootDir).canonicalFile }.getOrNull()
    }
    private val facadeNames = mutableMapOf<String, String>()

    public companion object {
        private const val GENERATOR_ID: String = "store-studio-ksp/0.1.0"
        private const val MANIFEST_PATH: String = "META-INF/store-studio/store-manifest"
        private const val MANIFEST_EXTENSION: String = "json"
        private val ID_REGEX: Regex = Regex("^[a-z0-9_-]+$")
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        // Collect screenshot annotations across all compilation units
        val screenshotSymbols = resolver
            .getSymbolsWithAnnotation(StoreScreenshot::class.qualifiedName!!)
        for (symbol in screenshotSymbols) {
            val entry = processScreenshotFunction(symbol)
            if (entry != null && symbol is KSFunctionDeclaration) {
                entries.add(entry)
                symbol.containingFile?.let { originatingFiles.add(it) }
            }
        }

        // Collect feature graphic declarations for Play Store promotional banners
        val featureSymbols = resolver
            .getSymbolsWithAnnotation(StoreFeatureGraphic::class.qualifiedName!!)
        for (symbol in featureSymbols) {
            val entry = processFeatureGraphicFunction(symbol)
            if (entry != null && symbol is KSFunctionDeclaration) {
                entries.add(entry)
                symbol.containingFile?.let { originatingFiles.add(it) }
            }
        }

        return emptyList()
    }

    override fun finish() {
        // Write the consolidated manifest when valid annotated declarations are present
        if (originatingFiles.isNotEmpty()) {
            writeManifest(entries, originatingFiles)
        }
    }

    private fun processScreenshotFunction(symbol: KSAnnotated): ManifestEntry? {
        if (symbol !is KSFunctionDeclaration) {
            logger.error("Store Studio: @StoreScreenshot can only be applied to functions.", symbol)
            return null
        }

        val annotation = findAnnotation(symbol, StoreScreenshot::class.qualifiedName!!)
            ?: return null

        val fqn = resolveJvmFqn(symbol)
        if (!validateFunction(symbol, "StoreScreenshot", fqn)) return null

        val id = parseStringArg(annotation, "id") ?: symbol.simpleName.asString()
        if (!validateId(id, symbol, "StoreScreenshot")) return null

        val order = parseIntArg(annotation, "order", default = 0)
        if (order < 0) {
            logger.error(
                "Store Studio: Invalid order '$order' for @StoreScreenshot '$id'. " +
                    "Order must be greater than or equal to 0.",
                symbol,
            )
            return null
        }

        val name = parseStringArg(annotation, "name")
        val title = if (!name.isNullOrBlank()) name else null
        val devices = parseEnumArgList<DeviceFamily>(annotation, "devices")
        val targets = parseEnumArgList<StoreTarget>(annotation, "targets")
        val locales = parseStringListArg(annotation, "locales")
        val source = resolveSourceLocation(symbol)

        if (!checkDuplicateId(id, source, symbol, "StoreScreenshot")) return null

        return ManifestEntry(
            kind = EntryKind.SCREENSHOT,
            id = id,
            order = order,
            title = title,
            functionFqn = fqn,
            packageName = symbol.packageName.asString(),
            functionName = symbol.simpleName.asString(),
            devices = devices,
            targets = targets,
            locales = locales,
            source = source,
        )
    }

    private fun processFeatureGraphicFunction(symbol: KSAnnotated): ManifestEntry? {
        if (symbol !is KSFunctionDeclaration) {
            logger.error(
                "Store Studio: @StoreFeatureGraphic can only be applied to functions.",
                symbol,
            )
            return null
        }

        val annotation = findAnnotation(symbol, StoreFeatureGraphic::class.qualifiedName!!)
            ?: return null

        val fqn = resolveJvmFqn(symbol)
        if (!validateFunction(symbol, "StoreFeatureGraphic", fqn)) return null

        val id = parseStringArg(annotation, "id") ?: symbol.simpleName.asString()
        if (!validateId(id, symbol, "StoreFeatureGraphic")) return null

        val name = parseStringArg(annotation, "name")
        val title = if (!name.isNullOrBlank()) name else null
        val locales = parseStringListArg(annotation, "locales")
        val source = resolveSourceLocation(symbol)

        if (!checkDuplicateId(id, source, symbol, "StoreFeatureGraphic")) return null

        return ManifestEntry(
            kind = EntryKind.FEATURE_GRAPHIC,
            id = id,
            order = 0,
            title = title,
            functionFqn = fqn,
            packageName = symbol.packageName.asString(),
            functionName = symbol.simpleName.asString(),
            devices = emptyList(),
            targets = listOf(StoreTarget.PLAY_STORE),
            locales = locales,
            source = source,
        )
    }

    private fun validateFunction(
        function: KSFunctionDeclaration,
        annotationName: String,
        functionFqn: String,
    ): Boolean {
        // Verify the function is top-level to allow static reflection invocation
        val isTopLevel = function.parentDeclaration == null && function.containingFile != null
        if (!isTopLevel) {
            logger.error(
                "Store Studio: @$annotationName function '${function.simpleName.asString()}' " +
                    "must be a top-level function. Class member composables are not supported.",
                function,
            )
            return false
        }

        // Ensure the target function is marked as a Compose component
        if (!isComposable(function)) {
            logger.error(
                "Store Studio: @$annotationName function '$functionFqn' must be " +
                    "annotated with @Composable.",
                function,
            )
            return false
        }

        // Reject functions requiring parameters; standalone screenshots must provide own state
        if (function.parameters.isNotEmpty()) {
            logger.error(
                "Store Studio: @$annotationName function '$functionFqn' must have 0 parameters. " +
                    "Parameters are not supported, not even with default values. " +
                    "Move state inside the composable or wrap it in a zero-argument function.",
                function,
            )
            return false
        }

        // Verify visibility so that runtime reflection can access and invoke the composable
        if (function.isPrivate() || function.isProtected()) {
            logger.error(
                "Store Studio: @$annotationName function '$functionFqn' cannot be private. " +
                    "Make it public or internal so the renderer can access it.",
                function,
            )
            return false
        }

        return true
    }

    private fun validateId(
        id: String,
        declaration: KSDeclaration,
        annotationName: String,
    ): Boolean {
        if (!ID_REGEX.matches(id)) {
            logger.error(
                "Store Studio: Invalid @$annotationName id '$id'. " +
                    "IDs must only contain lowercase alphanumeric characters, underscores, " +
                    "and dashes: ^[a-z0-9_-]+$",
                declaration,
            )
            return false
        }
        return true
    }

    private fun checkDuplicateId(
        id: String,
        location: SourceLocation,
        declaration: KSDeclaration,
        annotationName: String,
    ): Boolean {
        val existing = idToLocationMap[id]
        if (existing != null) {
            logger.error(
                "Store Studio: Duplicate @$annotationName id '$id' declared in " +
                    "'${existing.path}:${existing.line}' and " +
                    "'${location.path}:${location.line}'. " +
                    "IDs must be globally unique per module.",
                declaration,
            )
            return false
        }
        idToLocationMap[id] = location
        return true
    }

    private fun isComposable(function: KSFunctionDeclaration): Boolean {
        return function.annotations.any { annotation ->
            val name = annotation.shortName.asString()
            if (name != "Composable") return@any false
            val resolved = runCatching {
                annotation.annotationType.resolve().declaration.qualifiedName?.asString()
            }.getOrNull()
            // null: annotation type not resolvable (e.g. error type), keep trusting the short name
            resolved == null || resolved == "androidx.compose.runtime.Composable"
        }
    }

    internal fun resolveJvmFqn(function: KSFunctionDeclaration): String {
        val packageName = function.packageName.asString()
        val containingFile = function.containingFile
            ?: error("No containing file for ${function.simpleName.asString()}")

        val facadeName = facadeNames.getOrPut(containingFile.filePath) {
            facadeName(containingFile)
        }

        val methodName = function.simpleName.asString()
        return if (packageName.isEmpty()) {
            "$facadeName.$methodName"
        } else {
            "$packageName.$facadeName.$methodName"
        }
    }

    /** The JVM class holding [file]'s top-level functions, honoring `@file:JvmName`. */
    private fun facadeName(file: KSFile): String {
        val jvmNameAnnotation = file.annotations.firstOrNull {
            it.shortName.asString() == "JvmName" &&
                it.annotationType.resolve().declaration.qualifiedName?.asString() ==
                "kotlin.jvm.JvmName"
        }
        val defaultName = defaultFacadeName(file.fileName)
        if (jvmNameAnnotation == null) return defaultName
        val nameArg = jvmNameAnnotation.arguments.firstOrNull { it.name?.asString() == "name" }
            ?: jvmNameAnnotation.arguments.firstOrNull()
        return (nameArg?.value as? String) ?: defaultName
    }

    /**
     * Mirrors the Kotlin compiler's file facade naming: non-identifier characters become `_`,
     * the first character is capitalized, and `Kt` is appended
     * (`screens.kt` -> `ScreensKt`, `Screens.android.kt` -> `Screens_androidKt`).
     */
    internal fun defaultFacadeName(fileName: String): String {
        val stem = fileName.removeSuffix(".kt")
        val sanitized = buildString(stem.length + 1) {
            if (stem.isEmpty() || !Character.isJavaIdentifierStart(stem[0])) append('_')
            stem.forEach { append(if (Character.isJavaIdentifierPart(it)) it else '_') }
        }
        return sanitized.replaceFirstChar { it.uppercaseChar() } + "Kt"
    }

    /**
     * Finds the annotation with [qualifiedName], resolving types only for candidates whose short
     * name matches, and falling back to a full scan to support import aliases.
     */
    private fun findAnnotation(symbol: KSAnnotated, qualifiedName: String): KSAnnotation? {
        val simpleName = qualifiedName.substringAfterLast('.')
        fun KSAnnotation.resolvesTo(): Boolean =
            annotationType.resolve().declaration.qualifiedName?.asString() == qualifiedName
        return symbol.annotations.firstOrNull {
            it.shortName.asString() == simpleName &&
                it.resolvesTo()
        }
            ?: symbol.annotations.firstOrNull {
                it.shortName.asString() != simpleName && it.resolvesTo()
            }
    }

    internal fun resolveSourceLocation(function: KSFunctionDeclaration): SourceLocation {
        val containingFile = function.containingFile
        val line = (function.location as? FileLocation)?.lineNumber ?: 1
        val relativePath = if (containingFile != null) {
            try {
                val rootFile = canonicalRoot ?: error("unresolvable project root")
                val sourceFile = File(containingFile.filePath).canonicalFile
                sourceFile.relativeTo(rootFile).invariantSeparatorsPath
            } catch (_: Exception) {
                containingFile.filePath.replace('\\', '/')
            }
        } else {
            "unknown"
        }
        return SourceLocation(path = relativePath, line = line)
    }

    private fun writeManifest(entries: List<ManifestEntry>, originatingFiles: Set<KSFile>) {
        val manifest = StoreManifest(
            schemaVersion = 1,
            module = modulePath,
            generator = GENERATOR_ID,
            entries = entries.sortedBy { it.id },
        )

        val jsonContent = StoreManifest.encodeToString(manifest)
        val dependencies = Dependencies(aggregating = true, *originatingFiles.toTypedArray())

        val outputStream = codeGenerator.createNewFileByPath(
            dependencies = dependencies,
            path = MANIFEST_PATH,
            extensionName = MANIFEST_EXTENSION,
        )

        outputStream.bufferedWriter(Charsets.UTF_8).use { writer ->
            writer.write(jsonContent)
            writer.newLine()
        }
    }

    private fun parseStringArg(annotation: KSAnnotation, name: String): String? {
        val arg = annotation.arguments.firstOrNull { it.name?.asString() == name }
            ?: if (name == "id") annotation.arguments.firstOrNull() else null
        return arg?.value as? String
    }

    private fun parseIntArg(annotation: KSAnnotation, name: String, default: Int): Int {
        val arg = annotation.arguments.firstOrNull { it.name?.asString() == name }
        return when (val v = arg?.value) {
            is Int -> v
            is Number -> v.toInt()
            is String -> v.toIntOrNull() ?: default
            else -> default
        }
    }

    private fun parseStringListArg(annotation: KSAnnotation, name: String): List<String> {
        val arg = annotation.arguments.firstOrNull { it.name?.asString() == name }
            ?: return emptyList()
        return when (val v = arg.value) {
            is List<*> -> v.filterIsInstance<String>()
            is Array<*> -> v.filterIsInstance<String>()
            is String -> listOf(v)
            else -> emptyList()
        }
    }

    private inline fun <reified T : Enum<T>> parseEnumArgList(
        annotation: KSAnnotation,
        name: String,
    ): List<T> {
        val arg = annotation.arguments.firstOrNull { it.name?.asString() == name }
            ?: return emptyList()
        val rawNames: List<String> = when (val v = arg.value) {
            is List<*> -> v.mapNotNull(::extractEnumName)
            is Array<*> -> v.mapNotNull(::extractEnumName)
            else -> listOfNotNull(extractEnumName(v))
        }

        val enumEntries = enumValues<T>()
        return rawNames.mapNotNull { rawName ->
            enumEntries.firstOrNull { it.name == rawName }
        }
    }

    private fun extractEnumName(value: Any?): String? = when (value) {
        is String -> value
        is KSType -> value.declaration.simpleName.asString()
        is KSDeclaration -> value.simpleName.asString()
        else -> value?.toString()
    }
}
